const CARE_BY_MATERIAL = (material: string): string[] => {
  const m = material.toLowerCase();
  if (m.includes("wool") || m.includes("cashmere") || m.includes("merino"))
    return [
      "Dry clean, or hand wash cold with wool detergent",
      "Reshape and dry flat away from direct sunlight",
      "Store folded to protect the shape",
    ];
  if (m.includes("leather"))
    return ["Wipe with a soft dry cloth", "Condition occasionally with a neutral balm", "Keep away from prolonged moisture"];
  if (m.includes("linen"))
    return ["Machine wash cold on a gentle cycle", "Line dry in shade", "Warm iron while slightly damp"];
  return ["Machine wash cold with like colours", "Tumble dry low or line dry", "Warm iron on reverse if needed"];
};

